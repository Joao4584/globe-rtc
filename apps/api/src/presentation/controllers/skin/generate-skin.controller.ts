import { Controller, Get, HttpCode, HttpStatus, Query, Res } from '@nestjs/common';
import { ApiBearerAuth, ApiOperation, ApiResponse, ApiTags } from '@nestjs/swagger';
import { FastifyReply } from 'fastify';
import { SKIN_PARTS, SkinAnimation, SkinPart, SkinSelection } from '@globe-rtc/skin-generator';
import { GenerateSkinUseCase } from '@/application/skin/use-case/generate-skin.use-case';
import { GenerateSkinRequest } from '@/presentation/requests/skin/generate-skin.request';
import { GenerateSkinDocs } from './generate-skin.doc';

@ApiTags(GenerateSkinDocs.tags)
@ApiBearerAuth()
@Controller('skin')
export class GenerateSkinController {
  constructor(private readonly generateSkinUseCase: GenerateSkinUseCase) {}

  @HttpCode(HttpStatus.OK)
  @Get('generate')
  @ApiOperation(GenerateSkinDocs.operation)
  @ApiResponse(GenerateSkinDocs.response)
  @ApiResponse(GenerateSkinDocs.badRequest)
  async generate(@Query() query: GenerateSkinRequest, @Res() reply: FastifyReply) {
    const type = query.type ?? 'adult';
    const sheet = query.sheet === 'true';

    const skin = await this.generateSkinUseCase.execute({
      type,
      parts: this.parseParts(query.parts),
      current: this.parseCurrent(query, type),
      includeSpritesheet: sheet,
      animations: this.parseAnimations(query.animations),
    });

    // The seed (generated by the use case) and the selection are not in the PNG, so they travel in headers; browsers need them exposed to let a fetch() read them.
    reply.header('Cache-Control', 'no-store');
    reply.header('X-Skin-Seed', String(skin.seed));
    reply.header('X-Skin-Selection', JSON.stringify(skin.selection));
    reply.header('Access-Control-Expose-Headers', 'X-Skin-Seed, X-Skin-Selection');

    if (query.format === 'json') {
      return reply.send({
        seed: skin.seed,
        selection: skin.selection,
        preview: toDataUrl(skin.preview),
        spritesheet: skin.spritesheet ? toDataUrl(skin.spritesheet) : undefined,
        layout: skin.animationLayout,
      });
    }

    reply.header('Content-Type', 'image/png');
    return reply.send(sheet ? skin.spritesheet : skin.preview);
  }

  /** `outfit,hairstyle` -> ['outfit', 'hairstyle']. No `parts` means every part. Names are validated by the skin package. */
  private parseParts(parts?: string): SkinPart[] {
    if (parts === undefined) return [...SKIN_PARTS];
    return parts
      .split(',')
      .map((part) => part.trim())
      .filter(Boolean) as SkinPart[];
  }

  /** `idle,walk,sit` -> ['idle', 'walk', 'sit']. Names are validated by the skin package. */
  private parseAnimations(animations?: string): SkinAnimation[] | undefined {
    if (animations === undefined) return undefined;
    return animations
      .split(',')
      .map((name) => name.trim())
      .filter(Boolean) as SkinAnimation[];
  }

  /** Pieces sent in the query for the parts that should be kept. `none` means no hairstyle / no accessory. */
  private parseCurrent(query: GenerateSkinRequest, type: SkinSelection['type']): Partial<SkinSelection> | undefined {
    const current: Record<string, string | null> = {};
    for (const part of SKIN_PARTS) {
      const value = query[part];
      if (value !== undefined) current[part] = value === 'none' ? null : value;
    }
    return Object.keys(current).length > 0 ? { type, ...current } : undefined;
  }
}

function toDataUrl(png: Buffer): string {
  return `data:image/png;base64,${png.toString('base64')}`;
}
